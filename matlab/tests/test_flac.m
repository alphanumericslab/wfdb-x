    assert_eq(hex(wfdbx.internal.md5(typecast(int32(reshape(ch', 1, [])), 'uint8'))), ...
        ff{k, 4}, [ff{k, 1} ' samples']);
end

% Decoding errors (as libFLAC reports them)
assert_eq(flacerr(uint8('fLaX')), 'wfdbx:flac:sync', 'bad marker');
assert_eq(flacerr(uint8('fLa')), 'wfdbx:flac:meta', 'no marker');
b = readfile(fullfile(data, 'flac8.dat'));
assert_eq(flacerr(b(1:end-100)), 'wfdbx:flac:sync', 'truncated');
c = b;
c(end-10) = bitxor(c(end-10), 1);
assert_eq(flacerr(c), 'wfdbx:flac:crc', 'CRC mismatch');
assert_eq(flacerr([b, zeros(1, 50, 'uint8')]), 'wfdbx:flac:sync', ...
    'trailing zeros');
% an ID3v2 tag before the stream is skipped
[ch, ~] = wfdbx.internal.flac_decode([uint8('ID3'), uint8([4 0 0 0 0 0 3]), ...
    zeros(1, 3, 'uint8'), b]);
assert_eq(size(ch), [2 5000], 'ID3v2 tag skipped');

% Encoding: files identical to those written by the Python encoder
cases = {16, 2, 9000, [0 1], 1, 23563, '0f8d92a0a9f0cb39a8403e279236f0cc'; ...
    8, 3, 5000, [0 2 3], 1, 6059, '3d45bfc94844f44da47f32caab986f59'; ...
    24, 1, 4500, 1, 1, 13580, '077e254c1c7d3f27c2bd45256d445042'; ...
    16, 2, 300, [3 0], 2, 432, '5d6cf79938c826cd2373062e88df7e3e'};
for k = 1:size(cases, 1)
    [bps, nch, n, kinds, spf] = cases{k, 1:5};
    sigs = zeros(nch, n);
    for c = 1:nch
        sigs(c, :) = gensignal(n, kinds(c), 16 + c, bps);
    end
    fname = fullfile(d, sprintf('enc%d.dat', k));
    og = wfdbx.internal.OGData();
    og.fp = wfdbx.internal.wfdb_fopen(fname, 'wb');
    si = wfdbx.siginfo(nch);
    for c = 1:nch
        si(c).fmt = 500 + bps;
        si(c).spf = spf;
    end
    assert_eq(wfdbx.internal.flac_osinit(og, si, nch), 0, 'flac_osinit');
    assert_eq(og.bsize, nch * spf * 4, 'bsize');
    assert_eq(wfdbx.internal.flac_osopen(og), 0, 'flac_osopen');
    % samples in frame order (spf samples of each signal per frame)
    v = reshape(permute(reshape(sigs, nch, spf, n / spf), [2 1 3]), 1, []);
    if k == 4
        for j = 1:numel(v)          % one at a time
            wfdbx.internal.flac_putsamp(v(j), 500 + bps, og);
        end
    else                            % in pieces
        h = floor(numel(v) / 3);
        wfdbx.internal.flac_putsamps(v(1:h), 500 + bps, og);
        wfdbx.internal.flac_putsamps(v(h+1:end), 500 + bps, og);
    end
    wfdbx.internal.flac_osclose(og);
    assert(isempty(og.flac), 'og.flac cleared');
    og.fp.close();
    out = readfile(fname);
    assert_eq(numel(out), cases{k, 6}, sprintf('encoded size %d', k));
    assert_eq(hex(wfdbx.internal.md5(out)), cases{k, 7}, sprintf('encoded file %d', k));
    [ch, bps2] = wfdbx.internal.flac_decode(out);
    assert_eq(bps2, bps, 'round trip bps');
    assert(isequal(ch, sigs), 'round trip samples');

    % reading through the input glue (frame order, seeks, end of data)
    ig = wfdbx.internal.IGData();
    ig.fp = wfdbx.internal.wfdb_fopen(fname, 'rb');
    ig.seek = 1;        % (as isigopen sets it for a file that can seek)
    hs = struct('info', num2cell(si));
    assert_eq(wfdbx.internal.flac_isopen(ig, hs, nch), 0, 'flac_isopen');
    ig.stat = 1;
    x1 = wfdbx.internal.flac_getsamp(ig);
    [x2, st] = wfdbx.internal.flac_getsamps(ig, 9);
    assert_eq([x1, x2], v(1:10), 'flac_getsamp(s)');
    assert(all(st == 1), 'stat while reading');
    assert_eq(wfdbx.internal.flac_isseek(ig, 7), 1, 'flac_isseek');
    x = wfdbx.internal.flac_getsamps(ig, inf);
    assert_eq(x, v(7 * nch * spf + 1:end), 'samples after seek');
    [x, st] = wfdbx.internal.flac_getsamps(ig, 2);
    assert_eq([x, st], [0 0 0 0], 'past the end');
    assert_eq(wfdbx.internal.flac_isseek(ig, n / spf + 1), -1, 'seek out of range');
    assert_eq(wfdbx.internal.flac_isclose(ig), 0, 'flac_isclose');
    ig.fp.close();
end
end

function s = gensignal(n, kind, seed, bps)
% (the same signals as in the Python script that computed the digests)
r = zeros(1, n);
x = seed;
for i = 1:n
    x = mod(25173 * x + 13849, 65536);
    r(i) = x;
end
lim = 2^(bps - 1);
switch kind
    case 0          % random walk
        s = zeros(1, n);
        v = 0;
        for i = 1:n
            v = max(-lim, min(lim - 1, v + mod(r(i), 21) - 10));
            s(i) = v;
        end
    case 1          % noise, full range
        if bps <= 16
            s = mod(r, 2 * lim) - lim;
        else
            s = mod(r * 256 + mod(r, 256), 2 * lim) - lim;
        end
    case 2          % constant
        s = repmat(mod(r(1), lim), 1, n);
    otherwise       % sawtooth
        s = mod(0:n-1, 50) * 3 - 70;
end
end

function id = flacerr(b)
id = '';
try
    wfdbx.internal.flac_decode(b);
catch err
    id = err.identifier;
end
end

function h = hex(b)
h = lower(reshape(dec2hex(double(b), 2)', 1, []));
end

function b = readfile(name)
fid = fopen(name, 'rb');
b = fread(fid, inf, 'uint8=>uint8')';
fclose(fid);
end
