% MD5 (RFC 1321 test suite), pure MATLAB code and the fast version
tv = {'', 'd41d8cd98f00b204e9800998ecf8427e'; ...
    'a', '0cc175b9c0f1b6a831c399e269772661'; ...
    'abc', '900150983cd24fb0d6963f7d28e17f72'; ...
    'message digest', 'f96b697d7cb7938d525a2f31aaf161d0'; ...
    'abcdefghijklmnopqrstuvwxyz', 'c3fcd3d76192e4007dfb496cca67e13b'; ...
    ['ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'], ...
    'd174ab98d277d9f5a5611c2c9f419d9f'; ...
    repmat('1234567890', 1, 8), '57edf4a22be3c955ac49da2e2107b67a'};
for k = 1:size(tv, 1)
    assert_eq(hex(wfdbx.internal.md5_pure(tv{k, 1})), tv{k, 2}, ['md5_pure ' tv{k, 1}]);
    assert_eq(hex(wfdbx.internal.md5(tv{k, 1})), tv{k, 2}, ['md5 ' tv{k, 1}]);
end
x = uint8(mod((0:999) * 7 + 3, 256));     % bytes >= 128, several blocks
assert_eq(hex(wfdbx.internal.md5_pure(x)), hex(wfdbx.internal.md5(x)), 'md5 binary');

% Decoding the FLAC records of tests/data (digest: MD5 of the samples as
% little-endian 32-bit integers, channel after channel)
recs = {'flac8', 8, [2 5000], '60d7a379cffdddf1d25fd6359bbbb410'; ...
    'flac16', 16, [3 9000], '0a302d411092885c1e7c9c387a4a81b9'; ...
    'flac24', 24, [1 4500], '009556de1b80833f7f1d21d99c817729'; ...
    'flacmf', 16, [2 8642], '6124eeedeae44a8d1a57ddba2184c760'};
for k = 1:size(recs, 1)
    [ch, bps] = wfdbx.internal.flac_decode(readfile(fullfile(data, [recs{k, 1} '.dat'])));
    assert_eq(bps, recs{k, 2}, [recs{k, 1} ' bps']);
    assert_eq(size(ch), recs{k, 3}, [recs{k, 1} ' size']);
    assert_eq(hex(wfdbx.internal.md5(typecast(int32(reshape(ch', 1, [])), 'uint8'))), ...
        recs{k, 4}, [recs{k, 1} ' samples']);
end

