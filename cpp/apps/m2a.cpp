// This file is part of WFDB-x, an independent reimplementation of the WFDB
// Software Package in Python, C++, MATLAB/Octave, Rust, Julia, R and Kotlin.
//
// It is a C++ translation of convert/m2a.c from the WFDB Software Package
// 10.7.0, by George B. Moody. The translation follows the logic and behavior
// of the original program, but it is new code, not the original C code.
//
// Changes from the original: no built-in sampling frequency: the new option -F
// FREQ gives it when the record header gives none, and is then required for -s
// (the original assumed 250 Hz); --legacy, as the first argument, restores the
// original behavior. Each change is marked "wfdb-x:" in the code;
// docs/DIVERGENCES.md gives the reasons.
//
// Original C program: convert/m2a.c, WFDB Software Package 10.7.0.
//   Copyright (C) 2001 George B. Moody.
// C++ translation and changes: Copyright (C) 2026 Reza Sameni.
//
// This program is free software: you can redistribute it and/or modify it
// under the terms of the GNU General Public License as published by the Free
// Software Foundation, either version 3 of the License, or (at your option)
// any later version. See LICENSE.
//
// The files generated by this program are in the format formerly used for
// distribution of the AHA and MIT-BIH databases on half-inch 9-track digital
// tape.  This program is provided as a convenience for those who may have
// software that requires files in AHA tape format as input.  It does *not*
// generate files in the format currently used for distribution of the AHA
// database on floppy disk;  program `a2m' can perform the reverse conversion,
// however.

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>

#include <wfdbx/wfdb.hpp>

using namespace wfdbx;

static const char *pname;

static const char *prog_name(const char *s)
{
    const char *p = s + std::strlen(s);
    while (p >= s && *p != '/') p--;
    return p + 1;
}

static const char *help_strings[] = {
    "usage: %s -r RECORD -a MIT-ANNOTATOR AHA-ANNOTATOR [ OPTIONS ... ]\n",
    "where RECORD is the record name, MIT-ANNOTATOR is the annotator name",
    "for the input annotation file, AHA-ANNOTATOR is the annotator name",
    "for the output (AHA format) annotation file, and OPTIONS may include:",
    " -F FREQ   sampling frequency, if the record header does not specify one",
    " -h        print this usage summary",
    " -s TIME   shift annotation times backwards by the specified TIME,",
    "            and convert them to milliseconds",
    nullptr
};

// wfdb-x: the help text of the original program, printed in legacy mode
static const char *legacy_help_strings[] = {
    "usage: %s -r RECORD -a MIT-ANNOTATOR AHA-ANNOTATOR [ OPTIONS ... ]\n",
    "where RECORD is the record name, MIT-ANNOTATOR is the annotator name",
    "for the input annotation file, AHA-ANNOTATOR is the annotator name",
    "for the output (AHA format) annotation file, and OPTIONS may include:",
    " -h        print this usage summary",
    " -s TIME   shift annotation times backwards by the specified TIME,",
    "            and convert them to milliseconds",
    nullptr
};

static void help()
{
    // wfdb-x: the original help text in legacy mode
    const char **hs = wfdbx_get_legacy() ? legacy_help_strings : help_strings;

    std::fprintf(stderr, hs[0], pname);
    for (int i = 1; hs[i] != nullptr; i++)
        std::fprintf(stderr, "%s\n", hs[i]);
}

// Exit after reporting an unrecognized option (wfdb-x: also the WFDB-x
// options, in legacy mode).
[[noreturn]] static void unrecognized(const char *arg)
{
    std::fprintf(stderr, "%s: unrecognized option %s\n", pname, arg);
    std::exit(1);
}

int main(int argc, char **argv)
{
    // wfdb-x: --legacy as the first argument selects legacy mode (the
    // behavior of the original program; see src/signal.cpp)
    wfdbx_legacy_args(argc, argv);

    const char *ianame = nullptr, *oaname = nullptr, *record = nullptr,
               *shift = nullptr;
    double Ffreq = 0.;
    int i;
    WFDB_Anninfo afarray[2];
    WFDB_Annotation annot;

    pname = prog_name(argv[0]);
    for (i = 1; i < argc; i++) {
        if (*argv[i] == '-') switch (*(argv[i] + 1)) {
            case 'a': // annotator names follow
                if (++i >= argc - 1) {
                    std::fprintf(stderr,
                       "%s: input and output annotator names must follow -a\n",
                                 pname);
                    std::exit(1);
                }
                ianame = argv[i++];
                oaname = argv[i];
                break;
            case 'F': // sampling frequency follows (WFDB-x)
                if (wfdbx_get_legacy())   // wfdb-x: not in the original
                    unrecognized(argv[i]);
                if (++i >= argc || std::sscanf(argv[i], "%lf", &Ffreq) != 1 ||
                    Ffreq <= 0.) {
                    std::fprintf(stderr,
                                 "%s: sampling frequency (> 0) must follow -F\n",
                                 pname);
                    std::exit(1);
                }
                break;
            case 'h': // help requested
                help();
                std::exit(1);
                break;
            case 'r': // record name follows
                if (++i >= argc) {
                    std::fprintf(stderr, "%s: record name must follow -r\n",
                                 pname);
                    std::exit(1);
                }
                record = argv[i];
                break;
            case 's': // shift follows
                if (++i >= argc) {
                    std::fprintf(stderr, "%s: time shift must follow -s\n",
                                 pname);
                    std::exit(1);
                }
                shift = argv[i];
                break;
            default:
                unrecognized(argv[i]);
            }
        else {
            std::fprintf(stderr, "%s: unrecognized argument %s\n", pname,
                         argv[i]);
            std::exit(1);
        }
    }
    if (ianame == nullptr || oaname == nullptr || record == nullptr) {
        help();
        std::exit(1);
    }

    afarray[0].name = ianame;
    afarray[0].stat = WFDB_READ;
    afarray[1].name = oaname;
    afarray[1].stat = WFDB_AHA_WRITE;
    if (annopen(record, afarray, 2) < 0) // open files
        std::exit(2);
    if (shift == nullptr)
        while (getann(0, &annot) >= 0) // copy annotations to end of data
            (void)putann(0, &annot);
    else {
        WFDB_Time dt;
        double mssi; // milliseconds per sample interval

        // wfdb-x: no default sampling frequency (the C program assumed
        // 250 Hz if the record header did not specify one, as legacy mode
        // does); -F specifies one.
        if (sampfreq(record) <= 0.) {
            if (wfdbx_get_legacy())
                (void)setsampfreq(WFDB_DEFFREQ);
            else if (Ffreq > 0.)
                (void)setsampfreq(Ffreq);
            else {
                std::fprintf(stderr,
                             "%s: sampling frequency of record %s is not "
                             "specified (use -F)\n", pname, record);
                std::exit(1);
            }
        }
        mssi = 1000. / strtim("1");
        dt = strtim(shift);
        while (getann(0, &annot) >= 0)
            if (annot.time >= dt) {
                annot.time = (WFDB_Time)((annot.time - dt) * mssi);
                (void)putann(0, &annot);
            }
    }

    wfdbquit();
    std::exit(0);
}
