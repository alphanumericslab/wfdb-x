old <- getwd()
oldpath <- Sys.getenv("WFDB", unset = NA)
d <- tempfile("wfdbx-test")
dir.create(d)
setwd(d)
on.exit({
  setwd(old)
  if (is.na(oldpath)) Sys.unsetenv("WFDB") else Sys.setenv(WFDB = oldpath)
  unlink(d, recursive = TRUE)
  wfdbio_reset()
}, add = TRUE)
wf <- function(name, data) writeBin(if (is.character(data)) charToRaw(data) else as.raw(data), name)
rf <- function(name) readBin(name, "raw", file.size(name))
dir.create("sub")
wf("rec.hea", "rec 1 360\nrec.dat 16 200 12 0 0 0 0 MLII\n")
wf(file.path("sub", "srec.hea"), "srec 0\n")
wf(file.path("sub", "srec.atr"), c(0, 4, 1, 2, 255, 128))
wf("pathfile", ". sub\r\n")

# The WFDB path (legacy mode: wfdb-x reads from a single input directory,
# see test_files.R)
wfdbx_set_legacy(TRUE)
on.exit(wfdbx_set_legacy(FALSE), add = TRUE)
wfdbio_reset()
setwfdb(". sub;/x/y http://example.org/db")
st <- .wfdb_io
expect_equal(st$path_prefix, c(".", "sub", "/x/y", "http://example.org/db"), "parsed path")
expect_equal(st$path_type, c(0, 0, 0, 1), "path types")
expect_equal(getwfdb(), ". sub;/x/y http://example.org/db", "getwfdb")
expect_equal(Sys.getenv("WFDB"), ". sub;/x/y http://example.org/db", "setwfdb sets WFDB")
wfdb_parse_path("a:b c")
expect_equal(st$path_prefix, c("a", "b", "c"), "colon separators")
wfdb_parse_path("")
expect_equal(length(st$path_prefix), 0L, "empty path")

setwfdb("@pathfile")
expect_equal(getwfdb(), ". sub", "indirect path")

expect_equal(wfdbfile("hea", "rec"), "./rec.hea", "wfdbfile hea")
expect_equal(wfdbfile("hea", "rec.hea"), "./rec.hea", "wfdbfile strips .hea")
expect_equal(wfdbfile("rec.hea", NULL), "./rec.hea", "wfdbfile by name")
expect_equal(wfdbfile("dat", "rec"), NULL, "missing file")
expect_equal(wfdbfile(NULL, NULL), "sub/rec.dat", "last file name tried")
expect_equal(wfdbfile("atr", "srec"), "sub/srec.atr", "found in sub")
expect_equal(st$path_prefix, c(".", "sub"), "addtopath (already second)")
setwfdb("/nonexistent .")
wfdb_addtopath("sub/srec.hea")
expect_equal(st$path_prefix, c("sub", "/nonexistent", "."), "addtopath new")
wfdb_addtopath("/nonexistent/x.hea")
expect_equal(st$path_prefix, c("/nonexistent", "sub", "."), "addtopath move")
wfdb_addtopath("/x.hea")   # "/" matches "/nonexistent" (strncmp of 1 byte)
expect_equal(st$path_prefix, c("/nonexistent", "sub", "."), "addtopath root")
setwfdb(". sub")
expect_equal(wfdbfile("hea", "../rec"), NULL, "names with .. are refused")
expect_equal(wfdbfile("sub", NULL), NULL, "directories are not files")
expect_equal(wfdbfile("hea", "http://example.org/x"), NULL, "URLs are not supported")

setwfdb(". %r %1rx")
wfdb_setirec("a/sub")
expect_equal(wfdb_getirec(), "sub", "irec")
expect_equal(wfdbfile("hea", "srec"), "sub/srec.hea", "%r substitution")
expect_equal(.expand_irec("%1rx/%r/%%/%q%", "abc"), "ax/abc/%/q", "%r expansion")
setwfdb(". sub")

wfdbquiet()
expect_equal(wfdb_checkname("rec_1-a/b~", "record"), 0, "checkname ok")
expect_equal(wfdb_checkname("a.b", "record"), -1, "checkname bad")
expect_equal(wfdberror(), "init: illegal character 46 in record name\n", "wfdberror")
expect_equal(wfdb_checkname(rawToChar(as.raw(c(0x61, 200))), "annotator"), -1, "checkname high")
expect_equal(wfdberror(), "init: illegal character -56 in annotator name\n", "signed char")
expect_equal(wfdb_checkname("", "record"), -1, "checkname empty")
wfdbverbose()
expect_equal(wfdb_striphea("x.hea"), "x", "striphea")
expect_equal(wfdb_striphea(".hea"), ".hea", "striphea short")
wfdbio_reset()
expect_equal(wfdberror(), "WFDB library version 10.7.0 (Jun 10 2022).\n", "wfdberror version")
expect_equal(c(wfdbversion(), wfdbldflags(), wfdbcflags(), wfdbdefwfdb(), wfdbdefwfdbcal()),
             c("10.7.0", "", "", ". /usr/local/database http://physionet.org/physiobank/database",
               "wfdbcal"), "version strings")
setwfdb(". sub")

# reading
f <- wfdb_open("atr", "srec", WFDB_READ)
check(is_wfdb_file(f), "wfdb_open result")
expect_equal(wf_g16(f), 1024, "g16")
expect_equal(wf_tell(f), 2, "tell")
expect_equal(wf_getc(f), 1L, "getc")
expect_equal(wf_seek(f, 0, 0), 0, "seek")
expect_equal(wf_g32(f), 1024 * 65536 + 513, "g32")
expect_equal(wf_g16(f), -32513, "g16 negative")
check(!wf_feof(f), "not eof")
expect_equal(wf_getc(f), -1L, "getc at eof")
check(wf_feof(f), "eof")
expect_equal(wf_seek(f, -2, 2), 0, "seek from end")
expect_equal(wf_read(f, 10), as.raw(c(255, 128)), "read short")
expect_equal(wf_seek(f, 100, 0), 0, "seek past end")
expect_equal(wf_tell(f), 100, "tell past end")
expect_equal(wf_read(f, 4), raw(0), "read past end")
expect_equal(wf_g16(f), -1, "g16 at eof")
expect_equal(wf_seek(f, 1, 0), 0, "seek back")
expect_equal(wf_readall(f), as.raw(c(4, 1, 2, 255, 128)), "readall")
expect_equal(wf_close(f), 0, "close")
f <- wfdb_open("hea", "rec", WFDB_READ)
expect_equal(rawToChar(wf_getline(f)), "rec 1 360\n", "getline 1")
expect_equal(rawToChar(wf_getline(f)), "rec.dat 16 200 12 0 0 0 0 MLII\n", "getline 2")
expect_equal(wf_getline(f), raw(0), "getline eof")
check(wf_feof(f), "getline eof flag")
wf_clearerr(f)
check(!wf_feof(f), "clearerr")
wf_close(f)

wfdbx_set_legacy(FALSE)

# a file larger than the read buffer
big <- as.raw(rep_len(0:255, 200000))
writeBin(big, "big.dat")
f <- wfdb_fopen("big.dat", "rb")
expect_equal(wf_read(f, 3), big[1:3], "big read 1")
expect_equal(wf_read(f, 70000), big[4:70003], "big read across blocks")
expect_equal(wf_tell(f), 70003, "big tell")
expect_equal(wf_seek(f, -3, 1), 0, "big seek cur")
expect_equal(wf_getc(f), as.integer(big[70001]), "big getc")
expect_equal(wf_seek(f, 150000, 0), 0, "big seek far")
expect_equal(wf_read(f, 100000), big[150001:200000], "big read to end")
check(wf_feof(f), "big eof")
expect_equal(wf_seek(f, 10, 0), 0, "big seek start")
expect_equal(length(wf_readall(f)), 199990L, "big readall")
wf_close(f)

# writing
f <- wfdb_open("dat", "out", WFDB_WRITE)
check(!is.null(f), "open for writing")
expect_equal(wfdbfile(NULL, NULL), "out.dat", "output file name")
wf_p16(f, -2)
wf_p32(f, 65536 * 3 + 4)
wf_putc(f, 300)
wf_write(f, "ab")
wf_printf(f, "%d|%s\n", 7, "x")
expect_equal(wf_tell(f), 13, "tell while writing")
wf_close(f)
expect_equal(rf("out.dat"), as.raw(c(254, 255, 3, 0, 4, 0, 44, 97, 98, 55, 124, 120, 10)), "written bytes")
f <- wfdb_open("dat", "out", WFDB_APPEND)
wf_write(f, as.raw(1))
expect_equal(wf_tell(f), 14, "tell append")
wf_close(f)
expect_equal(length(rf("out.dat")), 14L, "append")
f <- wfdb_open("hea", "new/dir/rec", WFDB_WRITE)
check(!is.null(f), "directories created for output")
wf_close(f)
check(file.exists(file.path("new", "dir", "rec.hea")), "file in new dir")
f <- wfdb_open("hea", "new/", WFDB_WRITE)
wf_close(f)
check(file.exists(file.path("new", "new.hea")), "record dir/ = dir/dir")
# seek and overwrite while writing (as the FLAC writer does), and past the end
f <- wfdb_fopen("ow.dat", "wb")
wf_write(f, as.raw(1:10))
expect_equal(wf_seek(f, 2, 0), 0, "seek output")
wf_write(f, as.raw(c(99, 98)))
expect_equal(wf_seek(f, 0, 2), 0, "seek output end")
expect_equal(wf_tell(f), 10, "tell output end")
expect_equal(wf_seek(f, 3, 1), 0, "seek output past end")
wf_write(f, as.raw(7))
wf_close(f)
expect_equal(rf("ow.dat"), as.raw(c(1, 2, 99, 98, 5:10, 0, 0, 0, 7)), "overwrite and extend")

# resetwfdb (also called by wfdbquit) restores the path returned by the first
# getwfdb (only if getwfdb was called before setwfdb), and restores the
# string only: the search path is not parsed again (as in C,
# docs/KNOWN_C_BEHAVIORS.md).  (Legacy mode: in normal mode, see test_files.R.)
wfdbx_set_legacy(TRUE)
wfdbio_reset()
Sys.setenv(WFDB = ".")
expect_equal(getwfdb(), ".", "getwfdb from WFDB")
setwfdb("a b")
expect_equal(getwfdb(), "a b", "setwfdb before resetwfdb")
resetwfdb()
expect_equal(getwfdb(), ".", "resetwfdb")
expect_equal(wfdbfile("hea", "rec"), NULL, "resetwfdb does not parse the path")
setwfdb("c")
wfdbquit()
expect_equal(getwfdb(), ".", "wfdbquit calls resetwfdb")
wfdbio_reset()
setwfdb("x")
resetwfdb()
expect_equal(getwfdb(), "x", "resetwfdb without a first getwfdb")
wfdbquit()
expect_equal(getwfdb(), "x", "wfdbquit without a first getwfdb")
setwfdb(".")
expect_equal(wfdbfile("hea", "rec"), "./rec.hea", "path parsed by setwfdb")
wfdbx_set_legacy(FALSE)
if (is.na(oldpath)) Sys.unsetenv("WFDB") else Sys.setenv(WFDB = oldpath)
wfdbio_reset()

# wfdbmemerr / wfdb_me_fatal
expect_equal(wfdb_me_fatal(), 1, "wfdb_me_fatal default")
wfdbmemerr(0)
expect_equal(wfdb_me_fatal(), 0, "wfdbmemerr(0)")
wfdbmemerr(5)
expect_equal(wfdb_me_fatal(), 5, "wfdbmemerr(5)")
wfdbmemerr(1)
expect_equal(wfdb_me_fatal(), 1, "wfdbmemerr(1)")

# getinfo(NULL) after wfdb_freeinfo, with no current input record
wfdbio_reset()
wfdb_freeinfo()
wfdbquiet()
expect_equal(getinfo(NULL), NULL, "getinfo after wfdb_freeinfo, no record")
expect_equal(wfdberror(), "getinfo: caller did not specify record name\n",
             "getinfo after wfdb_freeinfo, no record: error")
wfdbverbose()
wfdbio_reset()
